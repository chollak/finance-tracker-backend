/** The board's records as the audit reads them: amounts in minor units, ids in the order of the board. */
export function prototypeRecords(): AuditRecord[] {
  return ROWS.map(([date, code, amount, note], index) => {
    const category = PROTOTYPE_CATEGORIES[code];
    return {
      id: `r${index + 1}`,
      date,
      amountMinor: amount * 100,
      categoryId: category.id,
      categoryName: category.name,
      categoryPresetKey: category.presetKey,
      note,
    };
  });
}
