-- Канал, через который транзакция попала в систему.
--
-- Добавлено 2026-08-27 отрезком «сжатие продукта до ядра захвата».
-- Нужно, чтобы отличать каналы, когда рядом с Telegram-ботом появится
-- Apple Shortcut, а позже — возможно, нативное приложение.
--
-- ВНИМАНИЕ: SupabaseTransactionRepository.create пишет колонку source явным
-- списком. Пока эта миграция не применена, вставки будут падать с ошибкой
-- про несуществующую колонку.
--
-- На 2026-08-27 к проекту не применены также 007 и 008 — а репозиторий уже
-- пишет semantic_type и needs_review, которые они добавляют. Перед возвратом
-- Supabase из паузы проверить реальное состояние схемы и применить всё
-- по порядку: 007, 008, затем 009.

alter table transactions
  add column if not exists source text;

comment on column transactions.source is
  'Канал захвата: telegram | shortcut | webapp. NULL у строк, созданных до 2026-08-27.';
