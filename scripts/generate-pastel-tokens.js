#!/usr/bin/env node
/*
 * Design tokens of «Пастель» → code (FT-092).
 *
 * Source of truth: docs/pastel/tokens.json (copied from the design-system artifact). This script
 * writes two files that must not be edited by hand:
 *   webapp/src/app/styles/pastel-tokens.css  — CSS variables for the light and dark themes and the
 *                                               type styles as Tailwind utilities (`type-*`);
 *   webapp/src/shared/config/pastelTokens.ts — the same colors for code that needs raw values
 *                                               (Telegram header colour, charts).
 *
 * Usage:
 *   npm run tokens:pastel          # regenerate after changing tokens.json
 *   npm run check:tokens           # fail if the generated files are out of date (part of verify)
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SOURCE = path.join(ROOT, 'docs', 'pastel', 'tokens.json');
const CSS_OUT = path.join(ROOT, 'webapp', 'src', 'app', 'styles', 'pastel-tokens.css');
const TS_OUT = path.join(ROOT, 'webapp', 'src', 'shared', 'config', 'pastelTokens.ts');

const HEADER = 'Generated by scripts/generate-pastel-tokens.js from docs/pastel/tokens.json — do not edit by hand.';

function themed(value) {
  return typeof value === 'object' && value !== null && 'light' in value && 'dark' in value;
}

function build(tokens) {
  const light = [];
  const dark = [];
  const colorsLight = {};
  const colorsDark = {};

  for (const token of tokens.color.tokens) {
    const name = token.name;
    if (themed(token.value)) {
      light.push(`  --${name}: ${token.value.light};`);
      dark.push(`  --${name}: ${token.value.dark};`);
      colorsLight[name] = token.value.light;
      colorsDark[name] = token.value.dark;
    } else {
      light.push(`  --${name}: ${token.value};`);
      colorsLight[name] = token.value;
      colorsDark[name] = token.value;
    }
  }

  for (const token of tokens.shadow.tokens) {
    light.push(`  --${token.name}: ${themed(token.value) ? token.value.light : token.value};`);
    if (themed(token.value)) dark.push(`  --${token.name}: ${token.value.dark};`);
  }

  // Radii and component sizes become Tailwind theme values: rounded-card, h-button, size-touch…
  // The 4px spacing steps (space-1…space-6) equal Tailwind's default scale (p-1 = 4px … p-6 = 24px).
  const theme = [];
  for (const token of tokens.radius.tokens) theme.push(`  --${token.name}: ${token.value};`);
  for (const token of tokens.size.tokens) theme.push(`  --spacing-${token.name.replace(/^size-/, '')}: ${token.value};`);

  const utilities = [];
  for (const group of tokens.type.groups) {
    for (const style of group.styles) {
      const rules = [
        `  font-size: ${style.fontSize};`,
        `  line-height: ${style.lineHeight};`,
        `  font-weight: ${style.fontWeight};`,
      ];
      if (style.letterSpacing) rules.push(`  letter-spacing: ${style.letterSpacing};`);
      rules.push('  font-variant-numeric: tabular-nums;');
      utilities.push(`/* ${style.usage} */\n@utility type-${style.name} {\n${rules.join('\n')}\n}`);
    }
  }

  const css = [
    `/* ${HEADER} */`,
    '',
    '@theme {',
    ...theme,
    '}',
    '',
    '/* Light theme is the default; [data-theme] on <html> is set by the theme controller (FT-092). */',
    ':root,',
    ':root[data-theme="light"] {',
    ...light,
    '}',
    '',
    ':root[data-theme="dark"] {',
    ...dark,
    '  color-scheme: dark;',
    '}',
    '',
    ...utilities.flatMap((utility) => [utility, '']),
  ].join('\n');

  const ts = [
    `// ${HEADER}`,
    '',
    `export const pastelColors = ${JSON.stringify({ light: colorsLight, dark: colorsDark }, null, 2)} as const;`,
    '',
    'export type PastelTheme = keyof typeof pastelColors;',
    'export type PastelColorName = keyof typeof pastelColors.light;',
    '',
  ].join('\n');

  return { css, ts };
}

const tokens = JSON.parse(fs.readFileSync(SOURCE, 'utf8'));
const { css, ts } = build(tokens);

if (process.argv.includes('--check')) {
  const stale = [
    [CSS_OUT, css],
    [TS_OUT, ts],
  ].filter(([file, content]) => !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content);
  if (stale.length > 0) {
    for (const [file] of stale) console.error(`✗ ${path.relative(ROOT, file)} is out of date — run npm run tokens:pastel`);
    process.exit(1);
  }
  console.log('✓ Pastel tokens are in sync with docs/pastel/tokens.json');
} else {
  fs.writeFileSync(CSS_OUT, css);
  fs.writeFileSync(TS_OUT, ts);
  console.log(`Wrote ${path.relative(ROOT, CSS_OUT)} and ${path.relative(ROOT, TS_OUT)}`);
}
