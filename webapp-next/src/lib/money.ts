/**
 * Суммы в сумах. Дробной части нет: копеек у сума на практике не бывает,
 * а число и так достигает тринадцати знаков с разделителями.
 */

/** Неразрывный пробел U+00A0. */
const NBSP = '\u00A0';

/**
 * Разделитель разрядов приводится к U+00A0 ЯВНО, а не оставляется как есть.
 *
 * toLocaleString('ru-RU') в текущем Node отдаёт именно его, но ICU в других
 * средах умеет отдавать узкий неразрывный U+202F — он заметно уже, и число
 * начинает выглядеть слипшимся. Разница невидима глазом и невидима в диффе,
 * поэтому фиксируем символ, а не надеемся на среду.
 *
 * Обычный пробел не годится вовсе: с ним «54 124 654» переносится по строкам
 * и разваливается на «54» и «124 654».
 */
export function formatAmount(amount: number): string {
  return Math.round(amount)
    .toLocaleString('ru-RU')
    .replace(/[\s\u00A0\u202F]/g, NBSP);
}

/**
 * Размер герой-цифры выбирается по числу знаков, а не подгоняется на глаз.
 *
 * Нижняя граница 40px не случайна: ниже цифра перестаёт быть доминантой,
 * и экран разваливается в набор равнозначных блоков — ровно то, от чего
 * продукт уходит.
 *
 * Типичный месяц — девять знаков (2 582 000, проверено по базе), поэтому
 * рабочий размер 46. Тринадцать знаков это редкий край, но композиция
 * обязана его держать.
 */
export function heroFontSize(amount: number): 40 | 46 | 52 {
  // Пороги заданы по ЦИФРАМ, а не по длине форматированной строки: разделители
  // зависят от локали, и правило на них поехало бы. На канве оно было записано
  // как «до 7 знаков — 52, до 10 — 46» и само себе противоречило: под ним
  // 54 124 654 дало бы 46, хотя нарисовано было 40.
  //
  //   до 999 999            52   короткий месяц, начало периода
  //   1 000 000 … 9 999 999 46   типичный месяц, 2 582 000 по базе
  //   от 10 000 000         40   редкий край
  const digits = String(Math.round(Math.abs(amount))).length;
  if (digits <= 6) return 52;
  if (digits <= 7) return 46;
  return 40;
}
